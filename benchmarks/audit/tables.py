"""Generate reviewable Markdown directly from schema-2 benchmark series."""

import json
import re
from pathlib import Path


def number(value):
    return f"{value:.3f}"


def markdown(report):
    phases = report["series"]
    rows = {}
    for phase in phases:
        if phase.get("supplemental"):
            continue
        for name, result in phase["benchmarks"].items():
            # Size overrides are separate rows; audit/default are matched by name.
            key = name if phase["size_set"] != "override" else f"{name}@{result['size']}"
            rows.setdefault(key, {})[phase["mode"]] = result
    lines = ["## Trunk baseline — " + phases[0]["start"].get("local", phases[0]["start"]["utc"])[:10], "",
             "Generated by `audit/compare.py --render` from the linked schema-2 JSON; times are CPU seconds.",
             "Native CPU/RSS sizes and round counts are recorded per series in JSON. Instructions/cache: audit sizes.",
             "Each ratio cell is ratio of medians / paired median [Q1, Q3]. Near-threshold CPU gates",
             "require the same-binary control to differ by <3% on both measures. `within noise` is unresolved.",
             "", "| Suite | Benchmark | CPU size | Fa / Goose CPU | Fa / Rust CPU | Fa / Goose Ir | Fa / Rust Ir | Control | Goose / Rust goal |",
             "| --- | --- | ---: | --- | --- | ---: | ---: | --- | --- |"]
    for name, row in sorted(rows.items()):
        cpu, profile = row.get("cpu", {}), row.get("profile", {})
        if "error" in cpu or not cpu:
            lines.append(f"| {cpu.get('suite', '—')} | `{name}` | {cpu.get('size', '—')} | {cpu.get('error', 'unmeasured')} | — | — | — | — | — |")
            continue
        def ratio(side):
            stats = cpu["comparisons"][side]
            return f"{number(stats['ratio_of_medians'])} / {number(stats['median'])} [{number(stats['q1'])}, {number(stats['q3'])}]"
        def instructions(side):
            if "fa" not in profile:
                return "—"
            return number(profile["fa"]["events"]["Ir"] / profile[side]["events"]["Ir"])
        control = cpu["control"]
        control_text = f"{number(control['ratio_of_medians'])}/{number(control['median'])} {'pass' if control['passes'] else 'fail'}"
        verdict = " / ".join(cpu["comparisons"][side]["verdict"] for side in ("goose", "rust"))
        lines.append(f"| {cpu.get('suite', '—')} | `{name}` | {cpu['size']} | {ratio('goose')} | {ratio('rust')} | {instructions('goose')} | {instructions('rust')} | {control_text} | {verdict} |")
    lines += ["", "### Absolute measurements", "",
              "RSS is a separate GNU-time run, in KiB; stripped executable size is in bytes.",
              "Wasm and Bun timings use the size shown, including process startup; errors are retained.",
              "", "| Benchmark | CPU Fa / Goose / Rust (s) | RSS Fa / Goose / Rust (KiB) | Size Fa / Goose / Rust (bytes) | Ir size | Ir Fa / Goose / Rust (M) | Secondary size | Wasm (s) | Bun (s) |",
              "| --- | --- | --- | --- | ---: | --- | ---: | --- | --- |"]
    for name, row in sorted(rows.items()):
        cpu, profile, secondary = (row.get(mode, {}) for mode in ("cpu", "profile", "secondary"))
        def triple(result, key, scale=1):
            if any(side not in result for side in ("fa", "goose", "rust")):
                return "—"
            return " / ".join(number(result[side][key] / scale) if scale != 1 or key == "cpu"
                              else str(result[side][key]) for side in ("fa", "goose", "rust"))
        ins = " / ".join(number(profile[side]["events"]["Ir"] / 1e6) for side in ("fa", "goose", "rust")) if "fa" in profile else "—"
        def target(name):
            result = secondary.get("targets", {}).get(name, {})
            if "cpu" in result:
                return number(result["cpu"])
            error = result.get("error", "—")
            code = re.search(r"\[(E-[A-Z]+-\d+|[A-Z]+\d+)\]", error)
            if code:
                return "refused " + code[1]
            memory = re.search(r"memory limit (\d+) KiB", error)
            if memory:
                return f"> {int(memory[1]) / 1024:g} MiB"
            return error.replace("\n", " ").replace("|", "\\|")[-120:]
        lines.append(f"| `{name}` | {triple(cpu, 'cpu')} | {triple(cpu, 'gnu_peak_rss_kib')} | {triple(cpu, 'stripped_bytes')} | {profile.get('size', '—')} | {ins} | {secondary.get('size', '—')} | {target('wasm')} | {target('bun')} |")
    return "\n".join(lines) + "\n"


def render(paths, destination, markdown_path):
    series = []
    for path in paths:
        data = json.loads(path.read_text())
        if data.get("schema") != 2:
            raise ValueError(f"{path}: unsupported benchmark schema")
        series.extend(data["series"] if "series" in data else [data])
    report = {"schema": 2, "series": series}
    if destination:
        destination.parent.mkdir(parents=True, exist_ok=True)
        destination.write_text(json.dumps(report, indent=2) + "\n")
    text = markdown(report)
    if markdown_path:
        markdown_path.parent.mkdir(parents=True, exist_ok=True)
        markdown_path.write_text(text)
    else:
        print(text)
