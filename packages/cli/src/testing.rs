//! `fa test`: the tests of the `*.test.fa` files, compiled with the
//! package and run with Bun.

use super::*;

/// `fa test [<package>] [--watch]` (advanced brief §18.2): runs the tests
/// of the `*.test.fa` files on Bun, each with freshly initialized
/// module-level values; exits with 0 when every test that ran passed, 1
/// otherwise.
pub(crate) fn test(arguments: &[OsString]) -> i32 {
	let mut paths = Vec::new();
	let mut watch = false;
	let mut asynchronous = None;
	for argument in arguments {
		let text = argument.to_string_lossy();
		if let Some(mode) = asynchronous_option(&text) {
			let Ok(mode) = mode else {
				eprintln!(
					"fa test: `{text}`: write `--asynchronous=true` or `--asynchronous=false`"
				);
				return USAGE;
			};
			asynchronous = Some(mode);
		} else if let Some(value) = text.strip_prefix("--target=") {
			if value != "bun" {
				eprintln!("fa test: only the `bun` target runs tests for now");
				return USAGE;
			}
		} else if text == "--watch" {
			watch = true;
		} else if text == "--coverage" {
			eprintln!("fa test: `--coverage` is not available yet: run the tests without it");
			return USAGE;
		} else if text.starts_with("--") {
			eprintln!("fa test: unknown option `{text}`");
			return USAGE;
		} else {
			paths.push(argument.clone());
		}
	}
	let path = match optional_path(&paths, "test") {
		Ok(path) => path,
		Err(code) => return code,
	};
	if watch {
		return match workspace::select(path.as_deref(), Implements::Tests) {
			Ok(selection) => develop::watch_tests(selection),
			Err(message) => {
				crate::color::eprintln_message(&message);
				1
			}
		};
	}
	on_selection(path.as_deref(), Implements::Tests, "test", |path| {
		// a package: on the parallel and streaming pipeline (an asynchronous
		// mode configured: its checks need the program, sequential)
		if pipeline_enabled()
			&& asynchronous.is_none()
			&& let Some(project) = streaming::locate(path)
			&& !configures_asynchronous(&project.base)
		{
			return stream_tests(project);
		}
		match Loaded::load(path, "bun") {
			Ok(mut loaded) => {
				loaded.configure_asynchronous(asynchronous, true);
				run_tests(&mut loaded)
			}
			Err(message) => {
				crate::color::eprintln_message(&message);
				1
			}
		}
	})
}

/// Whether the `package.fa` of a package sets `build.asynchronous`: the
/// checks of a configured asynchronous mode (`WCONC001`, `CONC010`) read
/// the whole program, so it runs on the sequential analysis.
pub(crate) fn configures_asynchronous(package: &Path) -> bool {
	workspace::package_configuration(package)
		.and_then(|value| value.field("build").cloned())
		.is_some_and(|build| build.field("asynchronous").is_some())
}

/// `fa test` of a package on the parallel and streaming pipeline: its
/// modules and test files are generated by the threads that analyze them
/// into the cache, then run with Bun.
pub(crate) fn stream_tests(project: project::Project) -> i32 {
	let directory = run_directory(&project.base.join("package.fa"));
	let purpose = streaming::Purpose {
		tests: true,
		quiet: false,
		replace: true,
	};
	let options = Options::new(Target::Bun, String::new());
	let main = match streaming::build(project, Target::Bun, &options, purpose, |_| directory) {
		streaming::Built::Written(modules) => modules[0].clone(),
		streaming::Built::Failed(code) => return code,
	};
	run_with_bun(&main, &[])
}

/// Runs the tests of a loaded package.
pub(crate) fn run_tests(loaded: &mut Loaded) -> i32 {
	crate::color::eprint_diagnostics(&loaded.rendered());
	if loaded.has_errors() {
		return 1;
	}
	let tests = loaded.inner.program.tests.clone();
	if tests.is_empty() {
		eprintln!("fa test: no test file (`*.test.fa`) in this package");
		return 0;
	}
	let focused = tests.iter().any(|&file| {
		let tree = loaded.session().tree(file);
		(0..tree.nodes.len()).any(|index| {
			matches!(
				fa_analyzer::syntax::view(tree, fa_analyzer::ids::NodeId::new(index)),
				fa_analyzer::syntax::View::Test {
					modifier: Some(fa_analyzer::syntax::TestModifier::Only),
					..
				}
			)
		})
	});
	if focused && let Some(reason) = project::focus_forbidden(&loaded.inner.project.base) {
		eprintln!(
			"error[TEST004]: a `test only` would hide the other tests, and {reason}: remove `only`"
		);
		return 1;
	}
	let mut options = Options::new(Target::Bun, loaded.shown.clone());
	options.libraries = loaded.c_libraries();
	let entry = fa_codegen_js::EntryOptions { tests: true };
	let generated = match loaded.generate_program(&options, &entry) {
		Ok(generated) => generated,
		Err(rendered) => {
			crate::color::eprint_diagnostics(&rendered);
			return 1;
		}
	};
	let base = loaded.inner.project.base.join("package.fa");
	let script = match write_run_script(&base, &generated) {
		Ok(script) => script,
		Err(error) => {
			eprintln!("fa test: can't write the compiled tests: {error}");
			return 1;
		}
	};
	run_with_bun(&script, &[])
}
