//! `fa test`: the tests of the `*.test.fa` files, compiled with the
//! package and run with Bun.

use super::*;

/// `fa test [<package>] [--watch]` (advanced brief §18.2): runs the tests
/// of the `*.test.fa` files on Bun, each with freshly initialized
/// module-level values; exits with 0 when every test that ran passed, 1
/// otherwise.
pub(crate) fn test(arguments: &[OsString]) -> i32 {
	let mut paths = Vec::new();
	let mut watch = false;
	let mut asynchronous = None;
	let mut native = false;
	for argument in arguments {
		let text = argument.to_string_lossy();
		if let Some(mode) = asynchronous_option(&text) {
			let Ok(mode) = mode else {
				eprintln!(
					"fa test: `{text}`: write `--asynchronous=true` or `--asynchronous=false`"
				);
				return USAGE;
			};
			asynchronous = Some(mode);
		} else if let Some(value) = text.strip_prefix("--target=") {
			match value {
				"bun" => native = false,
				"native" => native = true,
				_ => {
					eprintln!("fa test: the tests run on `bun` or `native`");
					return USAGE;
				}
			}
		} else if text == "--watch" {
			watch = true;
		} else if text == "--coverage" {
			eprintln!("fa test: `--coverage` is not available yet: run the tests without it");
			return USAGE;
		} else if text.starts_with("--") {
			eprintln!("fa test: unknown option `{text}`");
			return USAGE;
		} else {
			paths.push(argument.clone());
		}
	}
	let path = match optional_path(&paths, "test") {
		Ok(path) => path,
		Err(code) => return code,
	};
	if watch {
		return match workspace::select(path.as_deref(), Implements::Tests) {
			Ok(selection) => develop::watch_tests(selection),
			Err(message) => {
				crate::color::eprintln_message(&message);
				1
			}
		};
	}
	if native {
		// the LLVM backend is in `fa-native` (`native.rs`)
		let Some(backend) = crate::native::backend() else {
			return crate::native::delegate("test", arguments, "native");
		};
		return on_selection(path.as_deref(), Implements::Tests, "test", |path| {
			run_native_tests(backend, path, asynchronous)
		});
	}
	on_selection(path.as_deref(), Implements::Tests, "test", |path| {
		// a package: on the parallel and streaming pipeline (an asynchronous
		// mode configured: its checks need the program, sequential)
		if pipeline_enabled()
			&& asynchronous.is_none()
			&& let Some(project) = streaming::locate(path)
			&& !configures_asynchronous(&project.base)
		{
			return stream_tests(project);
		}
		match Loaded::load(path, "bun") {
			Ok(mut loaded) => {
				loaded.configure_asynchronous(asynchronous, true);
				run_tests(&mut loaded)
			}
			Err(message) => {
				crate::color::eprintln_message(&message);
				1
			}
		}
	})
}

/// Whether the `package.fa` of a package sets `build.asynchronous`: the
/// checks of a configured asynchronous mode (`WCONC001`, `CONC010`) read
/// the whole program, so it runs on the sequential analysis.
/// The asynchronous mode `build.asynchronous` of a package sets, if any.
pub(crate) fn configured_asynchronous(package: &Path) -> Option<bool> {
	match workspace::package_configuration(package)?
		.field("build")?
		.field("asynchronous")?
	{
		fa_analyzer::configuration::ConfigValue::Boolean(value) => Some(*value),
		_ => None,
	}
}

pub(crate) fn configures_asynchronous(package: &Path) -> bool {
	workspace::package_configuration(package)
		.and_then(|value| value.field("build").cloned())
		.is_some_and(|build| build.field("asynchronous").is_some())
}

/// `fa test` of a package on the parallel and streaming pipeline: its
/// modules and test files are generated by the threads that analyze them
/// into the cache, then run with Bun.
pub(crate) fn stream_tests(project: project::Project) -> i32 {
	let directory = run_directory(&project.base.join("package.fa"));
	let purpose = streaming::Purpose {
		tests: true,
		quiet: false,
		replace: true,
	};
	let options = Options::new(Target::Bun, String::new());
	let written = match streaming::build(project, Target::Bun, &options, purpose, |_| directory) {
		streaming::Built::Written(modules) => modules,
		streaming::Built::Failed(code) => return code,
	};
	let main = written[0].clone();
	let root = main.parent().map(Path::to_path_buf).unwrap_or_default();
	let paths: Vec<String> = written
		.iter()
		.filter_map(|path| path.strip_prefix(&root).ok())
		.map(|path| path.to_string_lossy().replace('\\', "/"))
		.collect();
	run_test_files(&main, &test_modules(paths.iter().map(String::as_str)))
}

/// Runs the tests of a loaded package.
pub(crate) fn run_tests(loaded: &mut Loaded) -> i32 {
	crate::color::eprint_diagnostics(&loaded.rendered());
	if loaded.has_errors() {
		return 1;
	}
	let tests = loaded.inner.program.tests.clone();
	if tests.is_empty() {
		eprintln!("fa test: no test file (`*.test.fa`) in this package");
		return 0;
	}
	let focused = tests.iter().any(|&file| {
		let tree = loaded.session().tree(file);
		(0..tree.nodes.len()).any(|index| {
			matches!(
				fa_analyzer::syntax::view(tree, fa_analyzer::ids::NodeId::new(index)),
				fa_analyzer::syntax::View::Test {
					modifier: Some(fa_analyzer::syntax::TestModifier::Only),
					..
				}
			)
		})
	});
	if focused && let Some(reason) = project::focus_forbidden(&loaded.inner.project.base) {
		eprintln!(
			"error[TEST004]: a `test only` would hide the other tests, and {reason}: remove `only`"
		);
		return 1;
	}
	let mut options = Options::new(Target::Bun, loaded.shown.clone());
	options.libraries = loaded.c_libraries();
	let entry = fa_codegen_js::EntryOptions { tests: true };
	let generated = match loaded.generate_program(&options, &entry) {
		Ok(generated) => generated,
		Err(rendered) => {
			crate::color::eprint_diagnostics(&rendered);
			return 1;
		}
	};
	let base = loaded.inner.project.base.join("package.fa");
	let script = match write_run_script(&base, &generated) {
		Ok(script) => script,
		Err(error) => {
			eprintln!("fa test: can't write the compiled tests: {error}");
			return 1;
		}
	};
	let modules = match &generated {
		JsBuild::Program(output) => {
			test_modules(output.modules.iter().map(|(path, _)| path.as_str()))
		}
		JsBuild::Single(_) => Vec::new(),
	};
	run_test_files(&script, &modules)
}

/// The modules of the test files among the paths of a program's
/// JavaScript modules (`library/greet.test.js` is `library/greet.test`).
fn test_modules<'p>(paths: impl IntoIterator<Item = &'p str>) -> Vec<String> {
	paths
		.into_iter()
		.filter(|path| !path.starts_with(fa_analyzer::mounts::DEPENDENCY_PREFIX))
		.filter_map(|path| path.strip_suffix(".js"))
		.filter(|module| module.ends_with(".test"))
		.map(str::to_string)
		.collect()
}

/// The line a test file's process ends its output with: its counts
/// (`faRunTests`, `--fa-test-file`).
const TEST_SUMMARY: &str = "\u{1}fa-test-summary ";

/// The number of test files run at once: `FA_TEST_WORKERS`, else the
/// number of cores.
fn test_workers() -> usize {
	std::env::var("FA_TEST_WORKERS")
		.ok()
		.and_then(|value| value.parse().ok())
		.filter(|&workers: &usize| workers > 0)
		.unwrap_or_else(|| std::thread::available_parallelism().map_or(1, usize::from))
}

/// The counts of a run of tests: passed, failed, skipped, not run.
#[derive(Clone, Copy, Debug, Default, PartialEq, Eq)]
struct Counts([u64; 4]);

impl Counts {
	fn add(&mut self, other: Counts) {
		for (total, count) in self.0.iter_mut().zip(other.0) {
			*total += count;
		}
	}

	/// The last line of the output of `faRunTests`.
	fn summary(&self) -> String {
		let [passed, failed, skipped, not_run] = self.0;
		let mut parts = vec![format!("{passed} passed"), format!("{failed} failed")];
		if skipped > 0 {
			parts.push(format!("{skipped} skipped"));
		}
		if not_run > 0 {
			parts.push(format!("{not_run} not run"));
		}
		parts.join(", ")
	}
}

/// Runs the tests of a compiled program (`main.js`), each test file in a
/// Bun process of its own, [`test_workers`] at once (decision "`fa test`
/// runs each test file in a process"): the outputs are printed in the
/// order of the files, each as soon as it and the files before it are
/// done, then the counts added up. A single test file runs in place.
pub(crate) fn run_test_files(main: &Path, modules: &[String]) -> i32 {
	if modules.len() <= 1 {
		return run_with_bun(main, &[]);
	}
	let Some(bun) = find_bun() else {
		eprintln!("{BUN_MISSING}");
		return 1;
	};
	let _ = std::io::stdout().flush();
	let workers = test_workers().min(modules.len());
	let next = std::sync::atomic::AtomicUsize::new(0);
	let mut totals = Counts::default();
	let mut crashed = false;
	std::thread::scope(|scope| {
		let (sender, receiver) = std::sync::mpsc::channel();
		for _ in 0..workers {
			let sender = sender.clone();
			let (next, bun) = (&next, &bun);
			scope.spawn(move || {
				loop {
					let index = next.fetch_add(1, std::sync::atomic::Ordering::SeqCst);
					let Some(module) = modules.get(index) else {
						break;
					};
					let output = Command::new(bun)
						.arg(main)
						.arg(format!("--fa-test-file={module}"))
						.stdin(std::process::Stdio::null())
						.output();
					if sender.send((index, output)).is_err() {
						break;
					}
				}
			});
		}
		drop(sender);
		let mut done = std::collections::BTreeMap::new();
		let mut printed = 0;
		for (index, output) in receiver {
			done.insert(index, output);
			while let Some(output) = done.remove(&printed) {
				match print_test_file(&modules[printed], output) {
					Some(counts) => totals.add(counts),
					None => {
						crashed = true;
						totals.add(Counts([0, 1, 0, 0]));
					}
				}
				printed += 1;
			}
		}
	});
	println!("\n{}", totals.summary());
	i32::from(crashed || totals.0[1] > 0)
}

/// Prints the output of a test file's process, and returns its counts;
/// `None` when it ended without them (reported as a failure).
fn print_test_file(module: &str, output: std::io::Result<std::process::Output>) -> Option<Counts> {
	let output = match output {
		Ok(output) => output,
		Err(error) => {
			println!("✗ {module}.fa: can't start Bun: {error}");
			return None;
		}
	};
	let stdout = String::from_utf8_lossy(&output.stdout);
	let (text, counts) = match stdout.rfind(TEST_SUMMARY) {
		Some(start) => {
			let counts: Vec<u64> = stdout[start + TEST_SUMMARY.len()..]
				.split_whitespace()
				.filter_map(|count| count.parse().ok())
				.collect();
			let counts = <[u64; 4]>::try_from(counts).ok().map(Counts);
			(&stdout[..start], counts)
		}
		None => (&stdout[..], None),
	};
	print!("{text}");
	let _ = std::io::stdout().flush();
	eprint!("{}", String::from_utf8_lossy(&output.stderr));
	if counts.is_none() {
		println!(
			"✗ {module}.fa: its tests didn't finish (exit code {})",
			exit_code(output.status)
		);
	}
	counts
}

/// `fa test --target=native`: the tests compiled by the LLVM backend into
/// one executable (`fa_codegen_llvm::compile_tests_linking`), run once per
/// test (its index as the argument: fresh module-level values, a stop ends
/// only its test), and reported like the Bun runner (`faRunTests`).
pub(crate) fn run_native_tests(
	backend: &dyn crate::native::Backend,
	path: Option<&Path>,
	asynchronous: Option<bool>,
) -> i32 {
	use fa_analyzer::syntax::{TestModifier, View};
	if !fa_codegen_llvm::llvm_available() {
		eprintln!(
			"fa: the `native` target needs the LLVM backend, and this `fa` was built without LLVM: run scripts/setup-llvm.sh, export LLVM_SYS_181_PREFIX and rebuild"
		);
		return 1;
	}
	let mut loaded = match Loaded::load(path, "native") {
		Ok(loaded) => loaded,
		Err(message) => {
			crate::color::eprintln_message(&message);
			return 1;
		}
	};
	loaded.configure_asynchronous(asynchronous, true);
	crate::color::eprint_diagnostics(&loaded.rendered());
	if loaded.has_errors() {
		return 1;
	}
	let session = loaded.session();
	let program = &loaded.inner.program;
	let tests = fa_codegen_llvm::program_tests(session, program);
	if tests.is_empty() {
		eprintln!("fa test: no test file (`*.test.fa`) in this package");
		return 0;
	}
	// what the runner reports: name, file, line, modifier
	let mut described: Vec<(String, String, usize, Option<TestModifier>)> = Vec::new();
	for &(file, test) in &tests {
		let tree = session.tree(file);
		let View::Test { name, modifier, .. } = fa_analyzer::syntax::view(tree, test) else {
			continue;
		};
		let text = match fa_analyzer::syntax::view(tree, name) {
			View::String(text) => text.to_string(),
			_ => tree.text(name.index()).trim_matches('"').to_string(),
		};
		let start = tree.spans[test.index()].start.min(tree.source.len());
		let line = tree.source[..start]
			.bytes()
			.filter(|&byte| byte == b'\n')
			.count() + 1;
		described.push((text, session.display_path(file), line, modifier));
	}
	let focused = described
		.iter()
		.any(|(_, _, _, modifier)| *modifier == Some(TestModifier::Only));
	if focused && let Some(reason) = project::focus_forbidden(&loaded.inner.project.base) {
		eprintln!(
			"error[TEST004]: a `test only` would hide the other tests, and {reason}: remove `only`"
		);
		return 1;
	}
	let directory =
		run_directory(&loaded.inner.project.base.join("package.fa")).with_file_name("native-tests");
	if let Err(error) = fs::create_dir_all(&directory) {
		eprintln!(
			"fa test: can't write into `{}`: {error}",
			directory.display()
		);
		return 1;
	}
	let options = fa_codegen_llvm::Options {
		asynchronous: Some(program.asynchronous),
		..fa_codegen_llvm::Options::default()
	};
	let artifact = match backend.compile(
		session,
		crate::native::Input::Tests(program),
		fa_codegen_llvm::Target::Native,
		&options,
		&directory.join("tests"),
		&fa_codegen_llvm::Libraries::default(),
	) {
		Ok(artifact) => artifact,
		Err(message) => {
			eprint!("{message}");
			return 1;
		}
	};
	let mut passed = 0;
	let mut failed = 0;
	let mut skipped = 0;
	let mut not_run = 0;
	let mut stopped: Option<&str> = None;
	for (index, (name, file, line, modifier)) in described.iter().enumerate() {
		let place = format!("{file}:{line}");
		if stopped == Some(file.as_str()) {
			not_run += 1;
			println!("- {name} ({place}): not run");
			continue;
		}
		if *modifier == Some(TestModifier::Skip)
			|| (focused && *modifier != Some(TestModifier::Only))
		{
			skipped += 1;
			continue;
		}
		let _ = std::io::Write::flush(&mut std::io::stdout());
		let output = Command::new(&artifact.output)
			.arg(index.to_string())
			.stdin(std::process::Stdio::null())
			.stdout(std::process::Stdio::inherit())
			.stderr(std::process::Stdio::piped())
			.output();
		let output = match output {
			Ok(output) => output,
			Err(error) => {
				eprintln!(
					"fa test: can't run `{}`: {error}",
					artifact.output.display()
				);
				return 1;
			}
		};
		let code = exit_code(output.status);
		if code == 0 {
			passed += 1;
			println!("✓ {name}");
			continue;
		}
		failed += 1;
		let (report, stops) = failure_report(&String::from_utf8_lossy(&output.stderr), code);
		if stops {
			stopped = Some(file.as_str());
		}
		println!("✗ {name} ({place})\n{report}");
	}
	let mut parts = vec![format!("{passed} passed"), format!("{failed} failed")];
	if skipped > 0 {
		parts.push(format!("{skipped} skipped"));
	}
	if not_run > 0 {
		parts.push(format!("{not_run} not run"));
	}
	println!("\n{}", parts.join(", "));
	i32::from(failed > 0)
}

/// What a failed run of a native test printed on stderr, as the Bun runner
/// reports it, and whether it stops the other tests of its file (a stop
/// other than an `assert`).
fn failure_report(stderr: &str, code: i32) -> (String, bool) {
	let stderr = stderr.trim_end();
	if let Some(rest) = stderr.strip_prefix("stop: assertion failed: ") {
		let condition = rest
			.rsplit_once("\n  at ")
			.map_or(rest, |(condition, _)| condition);
		return (
			format!("  assert {}", condition.replace("\n       ", "\n         ")),
			false,
		);
	}
	if stderr.starts_with("stop: ") || code == 101 {
		return (format!("  {stderr}"), true);
	}
	if let Some(error) = stderr.lines().find(|line| line.starts_with("error: ")) {
		return (format!("  {error}"), false);
	}
	(format!("  exited with {code}: {stderr}"), true)
}
