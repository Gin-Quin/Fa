//! The TypeScript declarations (`.d.ts`) of a generated module, so that
//! JavaScript and TypeScript code can import Fa modules with their types.
//!
//! A standalone file exports its entry function (its default export); the
//! modules of a program of several files export their declarations under
//! their export names (`numbers$increment`), declared as their JavaScript
//! is generated (`export_typings` of `generate/modules.rs`), into a `.d.ts`
//! next to each module.

use fa_analyzer::Session;
use fa_analyzer::ids::{FileId, NodeId, TypeId};
use fa_analyzer::syntax::{self, View};
use fa_analyzer::types::{CollKind, TypeKind, TypeStore};

/// The parameters (`a: number, b?: number`), the result type and whether
/// it is `async`, of the function whose value node is `value`.
pub(crate) fn signature(
	types: &TypeStore,
	analysis: &fa_analyzer::analysis::Analysis,
	value: NodeId,
) -> Option<(String, String, bool)> {
	let info = analysis.function(value)?;
	let sig = types.sig(info.sig?);
	let parameters: Vec<String> = info
		.params
		.iter()
		.zip(types.params(sig.params))
		.map(|(param, param_sig)| {
			let name = types
				.syms
				.resolve(analysis.symbols.symbol(param.symbol).name);
			// a name strict mode reserves (`arguments`): another one
			let name = if crate::names::is_reserved(name) {
				format!("{name}$")
			} else {
				name.to_string()
			};
			let optional = if param.default.is_some() { "?" } else { "" };
			if param.variadic {
				format!("...{name}: {}", typescript(types, param_sig.ty))
			} else {
				format!("{name}{optional}: {}", typescript(types, param_sig.ty))
			}
		})
		.collect();
	Some((
		parameters.join(", "),
		typescript(types, sig.ret),
		sig.is_async,
	))
}

/// The `.d.ts` of a file.
pub(crate) fn declarations(session: &Session, file: FileId) -> String {
	let tree = session.tree(file);
	let analysis = session.analysis(file);
	let types = session.types();
	let mut out = String::from("// Generated by fa: the types of the exports.\n");
	let root = NodeId::new(tree.root);
	let mut exported = false;
	if let View::Module { statements } = syntax::view(tree, root) {
		for statement in statements.iter() {
			if let View::ExportFunction { value, .. } = syntax::view(tree, statement)
				&& let Some(info) = analysis.function(value)
				&& let Some(sig) = info.sig
			{
				let sig = types.sig(sig);
				let parameters: Vec<String> = info
					.params
					.iter()
					.zip(types.params(sig.params))
					.map(|(param, param_sig)| {
						let name = types
							.syms
							.resolve(analysis.symbols.symbol(param.symbol).name);
						let optional = if param.default.is_some() { "?" } else { "" };
						if param.variadic {
							format!("...{name}: {}", typescript(types, param_sig.ty))
						} else {
							format!("{name}{optional}: {}", typescript(types, param_sig.ty))
						}
					})
					.collect();
				let ret = typescript(types, sig.ret);
				// an `async` function that may suspend: its default export is
				// the Promise API, and both instances are exported
				// (design/async.md §2.2, `generate/tasks.rs`)
				let suspends = [statement, value].iter().any(|key| {
					analysis
						.async_summaries
						.get(key)
						.is_some_and(|summary| summary.suspends)
				});
				if suspends && sig.is_async {
					let name = session
						.source_file(file)
						.interface
						.export_names
						.get(&statement)
						.cloned()
						.unwrap_or_else(|| "main".to_string());
					let parameters = parameters.join(", ");
					let task_first = if parameters.is_empty() {
						"task: unknown".to_string()
					} else {
						format!("task: unknown, {parameters}")
					};
					out.push_str(&format!(
						"/** Runs the call as a task: the promise rejects with its Fa error. */\nexport default function ({parameters}): Promise<{ret}>;\n/** The synchronous instance: a blocking call (Bun and Node). */\nexport declare function {name}$sync({parameters}): {ret};\n/** The async instance, for Fa modules: the caller's task first. */\nexport declare function {name}$async({task_first}): Promise<{ret}>;\n"
					));
				} else {
					out.push_str(&format!(
						"export default function ({}): {ret};\n",
						parameters.join(", "),
					));
				}
				exported = true;
			}
		}
	}
	if !exported {
		out.push_str("export {};\n");
	}
	out
}

/// The TypeScript spelling of a Fa type.
pub(crate) fn typescript(types: &TypeStore, ty: TypeId) -> String {
	match types.kind(ty) {
		TypeKind::Never => "never".to_string(),
		TypeKind::Void => "void".to_string(),
		TypeKind::None => "undefined".to_string(),
		TypeKind::Boolean | TypeKind::BoolLit(_) => "boolean".to_string(),
		TypeKind::Int(id) => {
			if types.int(id).storage.is_js_bigint() {
				"bigint".to_string()
			} else {
				"number".to_string()
			}
		}
		TypeKind::Float(_) | TypeKind::FloatLit(..) | TypeKind::Percentage => "number".to_string(),
		TypeKind::BigInt | TypeKind::BigIntLit(_) => "bigint".to_string(),
		TypeKind::String | TypeKind::StringLit(_) | TypeKind::Character => "string".to_string(),
		TypeKind::Union(list) => types
			.list_items(list)
			.iter()
			.map(|&member| typescript(types, member))
			.collect::<Vec<_>>()
			.join(" | "),
		TypeKind::Collection(CollKind::Array | CollKind::GrowingArray, item, _) => {
			format!("Array<{}>", typescript(types, item))
		}
		TypeKind::Object(_) => {
			let fields: Vec<String> = types
				.fields_of(ty)
				.iter()
				.map(|field| {
					format!(
						"{}: {}",
						types.syms.resolve(field.name),
						typescript(types, field.ty)
					)
				})
				.collect();
			format!("{{ {} }}", fields.join("; "))
		}
		TypeKind::Function(sig) => {
			let sig = types.sig(sig);
			let parameters: Vec<String> = types
				.params(sig.params)
				.iter()
				.enumerate()
				.map(|(index, param)| {
					if param.variadic {
						format!("...p{index}: {}[]", typescript(types, param.ty))
					} else {
						format!("p{index}: {}", typescript(types, param.ty))
					}
				})
				.collect();
			let ret = typescript(types, sig.ret);
			let parameters = parameters.join(", ");
			if !sig.is_async {
				return format!("({parameters}) => {ret}");
			}
			// a value of an `async` function type: its synchronous instance,
			// carrying its async one when it may suspend (`faAsyncValue`)
			let task_first = if parameters.is_empty() {
				"task: unknown".to_string()
			} else {
				format!("task: unknown, {parameters}")
			};
			format!("(({parameters}) => {ret}) & {{ $async?: ({task_first}) => Promise<{ret}> }}")
		}
		_ => "unknown".to_string(),
	}
}

#[cfg(test)]
mod tests {
	use super::*;

	#[test]
	fn scalar_types_map_to_typescript() {
		let types = TypeStore::new();
		assert_eq!(typescript(&types, TypeId::INTEGER), "number");
		assert_eq!(typescript(&types, TypeId::INT64), "bigint");
		assert_eq!(typescript(&types, TypeId::STRING), "string");
		assert_eq!(typescript(&types, TypeId::BOOLEAN), "boolean");
		assert_eq!(typescript(&types, TypeId::NONE), "undefined");
	}

	#[test]
	fn an_async_export_declares_its_two_instances() {
		let (session, file) = fa_analyzer::analyze_source(
			"use { sleep } = std.time\nexport async function = (arguments: Array<String>): Integer => {\n\tawait sleep(1)\n\targuments.length\n}\n",
		);
		let text = declarations(&session, file);
		assert!(
			text.contains("export default function (arguments: Array<string>): Promise<number>;"),
			"{text}"
		);
		assert!(
			text.contains("$sync(arguments: Array<string>): number;"),
			"{text}"
		);
		assert!(
			text.contains("$async(task: unknown, arguments: Array<string>): Promise<number>;"),
			"{text}"
		);
	}

	#[test]
	fn a_standalone_file_exports_nothing() {
		let (session, file) = fa_analyzer::analyze_source("let a = 1\n");
		assert!(declarations(&session, file).ends_with("export {};\n"));
	}
}
