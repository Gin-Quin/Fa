//! The TypeScript declarations (`.d.ts`) of a generated module, so that
//! JavaScript and TypeScript code can import Fa modules with their types.
//!
//! A standalone file exports nothing: its declarations are `export {};`.
//! Exports come with the multi-file modules of the analyzer (M2); the
//! mapping of types below is what they will use.

use fa_analyzer::Session;
use fa_analyzer::ids::{FileId, NodeId, TypeId};
use fa_analyzer::syntax::{self, View};
use fa_analyzer::types::{CollKind, TypeKind, TypeStore};

/// The `.d.ts` of a file.
pub(crate) fn declarations(session: &Session, file: FileId) -> String {
	let tree = session.tree(file);
	let analysis = session.analysis(file);
	let types = session.types();
	let mut out = String::from("// Generated by fa: the types of the exports.\n");
	let root = NodeId::new(tree.root);
	let mut exported = false;
	if let View::Module { statements } = syntax::view(tree, root) {
		for statement in statements.iter() {
			if let View::ExportFunction { value, .. } = syntax::view(tree, statement)
				&& let Some(info) = analysis.function(value)
				&& let Some(sig) = info.sig
			{
				let sig = types.sig(sig);
				let parameters: Vec<String> = info
					.params
					.iter()
					.zip(types.params(sig.params))
					.map(|(param, param_sig)| {
						let name = types
							.syms
							.resolve(analysis.symbols.symbol(param.symbol).name);
						let optional = if param.default.is_some() { "?" } else { "" };
						if param.variadic {
							format!("...{name}: {}", typescript(types, param_sig.ty))
						} else {
							format!("{name}{optional}: {}", typescript(types, param_sig.ty))
						}
					})
					.collect();
				out.push_str(&format!(
					"export default function ({}): {};\n",
					parameters.join(", "),
					typescript(types, sig.ret)
				));
				exported = true;
			}
		}
	}
	if !exported {
		out.push_str("export {};\n");
	}
	out
}

/// The TypeScript spelling of a Fa type.
pub(crate) fn typescript(types: &TypeStore, ty: TypeId) -> String {
	match types.kind(ty) {
		TypeKind::Never => "never".to_string(),
		TypeKind::Void => "void".to_string(),
		TypeKind::None => "undefined".to_string(),
		TypeKind::Boolean | TypeKind::BoolLit(_) => "boolean".to_string(),
		TypeKind::Int(id) => {
			if types.int(id).storage.is_js_bigint() {
				"bigint".to_string()
			} else {
				"number".to_string()
			}
		}
		TypeKind::Float(_) | TypeKind::FloatLit(..) | TypeKind::Percentage => "number".to_string(),
		TypeKind::BigInt | TypeKind::BigIntLit(_) => "bigint".to_string(),
		TypeKind::String | TypeKind::StringLit(_) | TypeKind::Character => "string".to_string(),
		TypeKind::Union(list) => types
			.list_items(list)
			.iter()
			.map(|&member| typescript(types, member))
			.collect::<Vec<_>>()
			.join(" | "),
		TypeKind::Collection(CollKind::Array | CollKind::GrowingArray, item, _) => {
			format!("Array<{}>", typescript(types, item))
		}
		TypeKind::Object(_) => {
			let fields: Vec<String> = types
				.fields_of(ty)
				.iter()
				.map(|field| {
					format!(
						"{}: {}",
						types.syms.resolve(field.name),
						typescript(types, field.ty)
					)
				})
				.collect();
			format!("{{ {} }}", fields.join("; "))
		}
		TypeKind::Function(sig) => {
			let sig = types.sig(sig);
			let parameters: Vec<String> = types
				.params(sig.params)
				.iter()
				.enumerate()
				.map(|(index, param)| {
					if param.variadic {
						format!("...p{index}: {}[]", typescript(types, param.ty))
					} else {
						format!("p{index}: {}", typescript(types, param.ty))
					}
				})
				.collect();
			format!(
				"({}) => {}",
				parameters.join(", "),
				typescript(types, sig.ret)
			)
		}
		_ => "unknown".to_string(),
	}
}

#[cfg(test)]
mod tests {
	use super::*;

	#[test]
	fn scalar_types_map_to_typescript() {
		let types = TypeStore::new();
		assert_eq!(typescript(&types, TypeId::INTEGER), "number");
		assert_eq!(typescript(&types, TypeId::INT64), "bigint");
		assert_eq!(typescript(&types, TypeId::STRING), "string");
		assert_eq!(typescript(&types, TypeId::BOOLEAN), "boolean");
		assert_eq!(typescript(&types, TypeId::NONE), "undefined");
	}

	#[test]
	fn a_standalone_file_exports_nothing() {
		let (session, file) = fa_analyzer::analyze_source("let a = 1\n");
		assert!(declarations(&session, file).ends_with("export {};\n"));
	}
}
