// Generates `fa_case_tables.h`, the Unicode case tables of `toUpperCase` and
// `toLowerCase` in the native runtime (`fa_string_case` of `fa_runtime.c`),
// from the JavaScript engine running it, so that native code converts case
// exactly as JavaScript does (design/decisions.md, "After the backends
// review"). Run by `generate.sh` (or `bun case_tables.js`), checked in.
//
// - The single code point mappings: runs of code points mapped by the same
//   delta, every code point of the run (stride 1) or every other one
//   (stride 2: the alternating upper and lower case pairs of Latin
//   Extended-A, Cyrillic...).
// - The mappings to several code points (`ß` → `SS`, `İ` → `i̇`), as UTF-8.
// - `Cased` and `Case_Ignorable`, as ranges: a capital sigma becomes a final
//   `ς` after a cased letter and not before one (Unicode's Final_Sigma).

import { writeFileSync } from "node:fs";

const LAST = 0x10ffff;

/** @param {number} code */
function isScalar(code) {
	return code < 0xd800 || code > 0xdfff;
}

/**
 * The single and multiple code point mappings of one direction.
 * @param {(text: string) => string} convert
 */
function mappings(convert) {
	/** @type {[number, number][]} */
	const single = [];
	/** @type {[number, string][]} */
	const multiple = [];
	for (let code = 0; code <= LAST; code += 1) {
		if (!isScalar(code)) continue;
		const text = String.fromCodePoint(code);
		const converted = convert(text);
		if (converted === text) continue;
		const points = Array.from(converted, (character) => /** @type {number} */ (character.codePointAt(0)));
		if (points.length === 1) {
			single.push([code, points[0] - code]);
		} else {
			multiple.push([code, converted]);
		}
	}
	return { single, multiple };
}

/**
 * Groups the single mappings into runs `[first, count, stride, delta]`.
 * @param {[number, number][]} single
 */
function runs(single) {
	/** @type {[number, number, number, number][]} */
	const result = [];
	let index = 0;
	while (index < single.length) {
		const [first, delta] = single[index];
		// the longest run of stride 1, then of stride 2
		let ones = 1;
		while (
			index + ones < single.length &&
			single[index + ones][0] === first + ones &&
			single[index + ones][1] === delta
		) {
			ones += 1;
		}
		let twos = 1;
		while (
			index + twos < single.length &&
			single[index + twos][0] === first + 2 * twos &&
			single[index + twos][1] === delta
		) {
			twos += 1;
		}
		if (twos > ones) {
			result.push([first, twos, 2, delta]);
			index += twos;
		} else {
			result.push([first, ones, 1, delta]);
			index += ones;
		}
	}
	return result;
}

/**
 * The ranges of the code points matching a property.
 * @param {RegExp} pattern
 */
function ranges(pattern) {
	/** @type {[number, number][]} */
	const result = [];
	for (let code = 0; code <= LAST; code += 1) {
		if (!isScalar(code) || !pattern.test(String.fromCodePoint(code))) continue;
		const last = result[result.length - 1];
		if (last !== undefined && last[1] === code - 1) {
			last[1] = code;
		} else {
			result.push([code, code]);
		}
	}
	return result;
}

/** @param {number} value */
const hex = (value) => `0x${value.toString(16).toUpperCase().padStart(4, "0")}`;

/**
 * The C escape of a UTF-8 string.
 * @param {string} text
 */
function cString(text) {
	return Array.from(new TextEncoder().encode(text), (byte) => `\\x${byte.toString(16).padStart(2, "0")}`).join("");
}

/**
 * Lines of at most 100 columns, each item followed by a comma.
 * @param {string[]} items
 */
function wrap(items) {
	const lines = [];
	let line = "   ";
	for (const item of items) {
		if (line.length + item.length + 2 > 100) {
			lines.push(line);
			line = "   ";
		}
		line += ` ${item},`;
	}
	if (line.trim() !== "") lines.push(line);
	return lines.join("\n");
}

const upper = mappings((text) => text.toUpperCase());
const lower = mappings((text) => text.toLowerCase());

/**
 * @param {string} name
 * @param {{ single: [number, number][], multiple: [number, string][] }} table
 */
function tables(name, table) {
	const grouped = runs(table.single);
	return [
		`static const CaseRun ${name}_RUNS[] = {`,
		wrap(grouped.map(([first, count, stride, delta]) => `{${hex(first)}, ${count}, ${stride}, ${delta}}`)),
		"};",
		`static const CaseSpecial ${name}_SPECIAL[] = {`,
		wrap(table.multiple.map(([code, text]) => `{${hex(code)}, "${cString(text)}"}`)),
		"};",
	].join("\n");
}

/**
 * @param {string} name
 * @param {[number, number][]} list
 */
function rangeTable(name, list) {
	return [
		`static const Range ${name}[] = {`,
		wrap(list.map(([first, last]) => `{${hex(first)}, ${hex(last)}}`)),
		"};",
	].join("\n");
}

const header = `// Generated by case_tables.js from the Unicode tables of the JavaScript
// engine (${typeof Bun === "undefined" ? "Node" : "Bun"}): do not edit. See fa_runtime.c, \`fa_string_case\`.

/// Code points \`first\`, \`first + stride\`… (\`count\` of them) map to
/// themselves plus \`delta\`.
typedef struct {
	uint32_t first;
	uint16_t count;
	uint8_t stride;
	int32_t delta;
} CaseRun;

/// A code point that maps to several (UTF-8, NUL-terminated).
typedef struct {
	uint32_t code;
	const char *text;
} CaseSpecial;

${tables("UPPER", upper)}

${tables("LOWER", lower)}

${rangeTable("CASED", ranges(/\p{Cased}/u))}

${rangeTable("CASE_IGNORABLE", ranges(/\p{Case_Ignorable}/u))}
`;

writeFileSync(new URL("./fa_case_tables.h", import.meta.url), header);
console.log("wrote fa_case_tables.h");
