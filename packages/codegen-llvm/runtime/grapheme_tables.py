#!/usr/bin/env python3
"""Generate Unicode 17 grapheme properties and official conformance cases.

Uses only checked-in Unicode data; regeneration never accesses the network.
The data and generated tables use the Unicode-3.0 license in unicode/17.0.0.
"""

from hashlib import sha256
from pathlib import Path


ROOT = Path(__file__).resolve().parent
DATA = ROOT / "unicode" / "17.0.0"
KINDS = {
    "Other": 0, "CR": 1, "LF": 2, "Control": 3, "Extend": 4, "ZWJ": 5,
    "Regional_Indicator": 6, "Prepend": 7, "SpacingMark": 8,
    "L": 9, "V": 10, "T": 11, "LV": 12, "LVT": 13,
}
HASHES = {
    "GraphemeBreakProperty.txt": "d6b51d1d2ae5c33b451b7ed994b48f1f4dc62b2272a5831e7fd418514a6bae89",
    "DerivedCoreProperties.txt": "24c7fed1195c482faaefd5c1e7eb821c5ee1fb6de07ecdbaa64b56a99da22c08",
    "emoji-data.txt": "2cb2bb9455cda83e8481541ecf5b6dfda66a3bb89efa3fa7c5297eccf607b72b",
    "GraphemeBreakTest.txt": "e2d134d2c52919bace503ebb6a551c1855fe1a1faec18478c78fff254a1793ec",
}


def source(name):
    raw = (DATA / name).read_bytes()
    assert sha256(raw).hexdigest() == HASHES[name], f"unexpected Unicode data: {name}"
    return raw.decode("utf-8")


def rows(name):
    for line in source(name).splitlines():
        fields = [field.strip() for field in line.split("#", 1)[0].split(";")]
        if len(fields) < 2:
            continue
        ends = fields[0].split("..")
        yield int(ends[0], 16), int(ends[-1], 16), fields[1:]


def properties():
    flags = bytearray(0x110000)
    for first, last, fields in rows("GraphemeBreakProperty.txt"):
        flags[first:last + 1] = bytes([KINDS[fields[0]]]) * (last - first + 1)
    for first, last, fields in rows("emoji-data.txt"):
        if fields[0] == "Extended_Pictographic":
            for code in range(first, last + 1):
                flags[code] |= 16
    indic = {"Consonant": 1, "Extend": 2, "Linker": 3}
    for first, last, fields in rows("DerivedCoreProperties.txt"):
        if fields[0] == "InCB":
            for code in range(first, last + 1):
                flags[code] |= indic[fields[1]] << 5
    # Hangul syllables use the exact algorithmic LV/LVT classification.
    for code in range(0xAC00, 0xD7A4):
        assert flags[code] == (12 if (code - 0xAC00) % 28 == 0 else 13)
        flags[code] = 0
    lines = [
        "// Generated by grapheme_tables.py; Unicode 17.0.0, UAX #29 revision 47.",
        "// SPDX-License-Identifier: Unicode-3.0; see unicode/17.0.0/LICENSE.txt.",
        "typedef struct { uint32_t first, last; uint8_t flags; } GraphemeRange;",
        "static const GraphemeRange FA_GRAPHEME_RANGES[] = {",
    ]
    first = 0
    while first < len(flags):
        last = first
        while last + 1 < len(flags) and flags[last + 1] == flags[first]:
            last += 1
        if flags[first]:
            lines.append(f"    {{0x{first:X}, 0x{last:X}, {flags[first]}}},")
        first = last + 1
    lines.append("};\n")
    (ROOT / "fa_grapheme_tables.h").write_text("\n".join(lines))


def tests():
    lines = [
        "// Generated official Unicode 17.0.0 GraphemeBreakTest cases.",
        "// SPDX-License-Identifier: Unicode-3.0; see ../unicode/17.0.0/LICENSE.txt.",
        "typedef struct { const uint8_t *bytes; size_t length; const uint16_t *ends; size_t count; } GraphemeCase;",
        "static const GraphemeCase FA_GRAPHEME_CASES[] = {",
    ]
    for line in source("GraphemeBreakTest.txt").splitlines():
        sequence = line.split("#", 1)[0].split()
        if not sequence:
            continue
        data, ends = bytearray(), []
        for token in sequence:
            if token == "÷":
                if data:
                    ends.append(len(data))
            elif token != "×":
                data.extend(chr(int(token, 16)).encode("utf-8", errors="surrogatepass"))
        assert len(data) < 0x10000
        text = "".join(f"\\x{byte:02X}" for byte in data)
        boundaries = ", ".join(str(end) for end in ends)
        lines.append(f'    {{(const uint8_t *)"{text}", {len(data)}, (const uint16_t[]){{{boundaries}}}, {len(ends)}}},')
    lines.append("};\n")
    (ROOT / "test" / "fa_grapheme_cases.h").write_text("\n".join(lines))


if __name__ == "__main__":
    properties()
    tests()
